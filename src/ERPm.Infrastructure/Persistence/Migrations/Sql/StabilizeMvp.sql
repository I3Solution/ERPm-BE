CREATE OR REPLACE FUNCTION erpm_uuid_v7() RETURNS uuid LANGUAGE plpgsql VOLATILE AS $$
DECLARE
    milliseconds bigint := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    bytes bytea := uuid_send(gen_random_uuid());
BEGIN
    bytes := overlay(bytes placing substring(int8send(milliseconds) from 3) from 1 for 6);
    bytes := set_byte(bytes, 6, (get_byte(bytes, 6) & 15) | 112);
    RETURN encode(bytes, 'hex')::uuid;
END;
$$;
