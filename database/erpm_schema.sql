-- RFC 9562 compliant UUIDv7 generator function for PostgreSQL
-- Produces monotonically increasing time-ordered UUIDs (48-bit Unix timestamp ms + version 7 + random)
CREATE OR REPLACE FUNCTION uuid_generate_v7()
RETURNS uuid
LANGUAGE plpgsql
VOLATILE
AS $$
DECLARE
    v_time timestamp with time zone := clock_timestamp();
    v_secs bigint := EXTRACT(EPOCH FROM v_time);
    v_msec bigint := MOD(EXTRACT(MILLISECONDS FROM v_time)::numeric, 1000::numeric);
    v_timestamp bigint := (v_secs * 1000) + v_msec;
    v_timestamp_hex varchar := LPAD(TO_HEX(v_timestamp), 12, '0');
    v_random_bytes bytea := gen_random_bytes(10);
    v_rand_a_hex varchar := LPAD(TO_HEX((get_byte(v_random_bytes, 0) & 15) | 112), 2, '0')
                            || LPAD(TO_HEX(get_byte(v_random_bytes, 1)), 2, '0');
    v_rand_b_hex varchar := LPAD(TO_HEX((get_byte(v_random_bytes, 2) & 63) | 128), 2, '0')
                            || SUBSTRING(ENCODE(v_random_bytes, 'hex') FROM 7 FOR 14);
BEGIN
    RETURN (
        SUBSTRING(v_timestamp_hex FROM 1 FOR 8) || '-' ||
        SUBSTRING(v_timestamp_hex FROM 9 FOR 4) || '-' ||
        v_rand_a_hex || '-' ||
        SUBSTRING(v_rand_b_hex FROM 1 FOR 4) || '-' ||
        SUBSTRING(v_rand_b_hex FROM 5 FOR 12)
    )::uuid;
END;
$$;

